import kagglehub
import os
import numpy             as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import tensorflow        as tf
from matplotlib.pyplot import imshow
import seaborn as sns
from sklearn.metrics   import confusion_matrix, roc_curve, classification_report
from tensorflow        import keras
from keras.models      import Sequential
from keras.utils       import image_dataset_from_directory
from keras.layers      import Conv2D, MaxPooling2D, Flatten, Dense, Dropout, GlobalAveragePooling2D

os.makedirs("resultados", exist_ok=True)

path = kagglehub.dataset_download("csafrit2/plant-leaves-for-image-classification")
print("Carpeta descargada: ", path)
print("Contenido:", os.listdir(path))

"""## **Datos**"""

RUTA_BASE = f"{path}/Plants_2"
IMG_SIZE = (160, 160)
BATCH_SIZE = 32

train_ds = image_dataset_from_directory(
    f"{RUTA_BASE}/train",
    shuffle=True,
    batch_size=BATCH_SIZE,
    image_size=IMG_SIZE,
    seed=42
)

val_ds = image_dataset_from_directory(
    f"{RUTA_BASE}/valid",
    shuffle=False,
    batch_size=BATCH_SIZE,
    image_size=IMG_SIZE,
)

test_ds = image_dataset_from_directory(
    f"{RUTA_BASE}/test",
    shuffle=False,
    batch_size=BATCH_SIZE,
    image_size=IMG_SIZE,
)

class_names = train_ds.class_names
print(class_names)

"""## Visualizamos las imagenes y las clases:"""

plt.figure(figsize=(7, 7))
for images, labels in train_ds.take(1):
    for i in range(22):
        ax = plt.subplot(5, 5, i + 1)
        plt.imshow(images[i].numpy().astype("uint8"))
        plt.title(class_names[labels[i]])
        plt.axis("off")
    print(labels)

AUTOTUNE = tf.data.AUTOTUNE

# Aplicamos únicamente Shuffle y Prefetch
train_ds = train_ds.prefetch(buffer_size=AUTOTUNE)
val_ds = val_ds.prefetch(buffer_size=AUTOTUNE)
test_ds = test_ds.prefetch(buffer_size=AUTOTUNE)
print("Datasets optimizados con Prefetch de forma segura.")

# 2. Análisis del balance de clases en el set de entrenamiento de forma rápida
ruta_train = f"{RUTA_BASE}/train"

# Obtenemos las clases y el número de archivos en cada una directamente desde el sistema de archivos
conteos = []
clases_encontradas = []

for name in class_names:
    ruta_clase = os.path.join(ruta_train, name)
    if os.path.isdir(ruta_clase):
        # Contamos cuántos archivos hay en el directorio de esta clase
        num_imagenes = len([f for f in os.listdir(ruta_clase) if os.path.isfile(os.path.join(ruta_clase, f))])
        # Dado que usamos validation_split=0.2, el set de entrenamiento real tiene el 80% de estas imágenes
        num_imagenes_train = int(num_imagenes * 0.8)
        conteos.append(num_imagenes_train)
        clases_encontradas.append(name)

# Visualizar la distribución de clases
plt.figure(figsize=(12, 6))
plt.barh(clases_encontradas, conteos, color='forestgreen')
plt.xlabel('Número aproximado de muestras en Entrenamiento (80%)')
plt.title('Distribución de Clases en el Conjunto de Entrenamiento')
plt.gca().invert_yaxis() # Clases con más frecuencia arriba
plt.grid(axis='x', linestyle='--', alpha=0.5)
plt.tight_layout()

"""## Mobilenet"""

IMG_SHAPE = IMG_SIZE + (3,)
base_model = tf.keras.applications.MobileNetV2(input_shape=IMG_SHAPE )

base_model.summary()

nb_layers = len(base_model.layers)
print(base_model.layers[nb_layers - 2].name)
print(base_model.layers[nb_layers - 1]. name)

image_batch, label_batch = next(iter(train_ds))
feature_batch = base_model(image_batch)
print(feature_batch.shape)

label_batch

