"""# Transfer Learning

## Mobilenet
"""

print(IMG_SIZE  )

IMG_SHAPE = IMG_SIZE + (3,)
pretrained_model_MobileNetV2 = tf.keras.applications.MobileNetV2(
    input_shape = IMG_SHAPE, # [96, 128, 160, 192, 224] No acepta imagenes mas grandes
    include_top = False,
    weights     = 'imagenet',
)

pretrained_model_MobileNetV2.trainable = False

pretrained_model_MobileNetV2.summary()

nb_layers = len(pretrained_model_MobileNetV2.layers)
print(nb_layers)
print(pretrained_model_MobileNetV2.layers[nb_layers - 2].name)
print(pretrained_model_MobileNetV2.layers[nb_layers - 1].name)
print(pretrained_model_MobileNetV2.layers[0].name)

image_batch, label_batch = next(iter(train_ds))
feature_batch = pretrained_model_MobileNetV2(image_batch)
print(feature_batch.shape)

"""## Nuevo modelo"""

inputs = tf.keras.Input(shape=IMG_SHAPE)
x = tf.keras.applications.mobilenet_v2.preprocess_input(inputs)
x = pretrained_model_MobileNetV2(x, training=False)

average_pooling = GlobalAveragePooling2D()(x)
drop = Dropout(0.2)(average_pooling)

outputs_MobileNetV2 = Dense(len(class_names), activation='softmax', name='prediccion')(drop)

modelo_MobileNetV2 = tf.keras.Model(inputs=inputs, outputs=outputs_MobileNetV2)
modelo_MobileNetV2.summary()

modelo_MobileNetV2.summary()

image_batch, label_batch = next(iter(train_ds))
feature_batch = modelo_MobileNetV2(image_batch)
print(feature_batch.shape)

base_learning_rate = 0.001

modelo_MobileNetV2.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=base_learning_rate),
    loss=tf.keras.losses.SparseCategoricalCrossentropy(from_logits=False),
    metrics=['accuracy']
)

print("Modelo configurado y compilado correctamente para clasificación de 22 clases.")

#Antes de entrenar
modelo_MobileNetV2.evaluate(train_ds)

import datetime
import zoneinfo
