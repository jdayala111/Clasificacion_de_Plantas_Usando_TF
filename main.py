"""## Resultados:"""

plt.figure(figsize=(12,12))

for images, labels in test_ds.unbatch().shuffle(500, seed=42).batch(9).take(1):
  preds = modelo_MobileNetV2.predict(images, verbose=0)
  pred_indices = np.argmax(preds, axis=1)

  for i in range(9):
    ax = plt.subplot(3, 3, i+1)
    plt.imshow(images[i].numpy().astype("uint8"))
    real_label = class_names[labels[i]]
    pred_label = class_names[pred_indices[i]]
    conf = np.max(preds[i]) * 100
    color = "green" if real_label == pred_label else "red"

    plt.title(f"Real: {real_label}\nPred: {pred_label} ({conf:.1f}%)",
              color=color, fontsize=9)
    plt.axis("off")

plt.tight_layout()
