history_MobileNetV2 = modelo_MobileNetV2.fit( train_ds, validation_data=val_ds,  epochs = initial_epochs_MobileNetV2)

"""## Gráficas"""

acc =  [0.] + history_MobileNetV2.history['accuracy']
